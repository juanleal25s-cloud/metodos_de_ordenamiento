    private void burbujabtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_burbujabtnActionPerformed
        try {
                // 1. Lee lo que escribiste en la caja: ej "5,2,9,1"
                String texto = Entrada.getText();

                if(texto.isEmpty()){
                    JOptionPane.showMessageDialog(null, "Escribe números");
                    return;
                }

                // 2. Convierte "5,2,9,1" a [5,2,9,1]
                String[] partes = texto.split(",");
                int[] arr = new int[partes.length];
                for(int i = 0; i < partes.length; i++){
                    arr[i] = Integer.parseInt(partes[i].trim());
                }

                // 3. Llama a tu clase Burbuja (usa el código corregido que te pasé)
                Burbuja.ordenar(arr);

                // 4. Muestra el resultado
                // Si tienes un lblResultado
                Entrega.setText(Arrays.toString(arr));

                // Si quieres mostrarlo en la misma caja
                // txtEntrada.setText(Arrays.toString(arr));

            } catch (HeadlessException | NumberFormatException ex) {
                JOptionPane.showMessageDialog(null, "Error: escribe así -> 5,2,9,1");
            }
        
    }//GEN-LAST:event_burbujabtnActionPerformed

